import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const manifestPath = path.join(root, "community", "capabilities.yml");
const outputPath = path.join(root, "COMMUNITY_FEATURES.md");
const allowedStatuses = new Set([
  "available",
  "configurable",
  "planned",
  "unavailable",
  "verification-needed",
]);

export function loadManifest(source = fs.readFileSync(manifestPath, "utf8")) {
  const manifest = JSON.parse(source);
  if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.capabilities)) {
    throw new Error("Unsupported capability manifest schema");
  }

  const ids = new Set();
  for (const capability of manifest.capabilities) {
    for (const field of ["id", "group", "name", "community", "requirements", "evidence"]) {
      if (typeof capability[field] !== "string" || capability[field].trim() === "") {
        throw new Error(`Capability ${capability.id ?? "<unknown>"} is missing ${field}`);
      }
    }
    if (ids.has(capability.id)) throw new Error(`Duplicate capability id: ${capability.id}`);
    if (!allowedStatuses.has(capability.community)) {
      throw new Error(`Unknown status ${capability.community} for ${capability.id}`);
    }
    ids.add(capability.id);
  }
  return manifest;
}

const labels = {
  available: "Available",
  configurable: "Configurable",
  planned: "Planned",
  unavailable: "Unavailable",
  "verification-needed": "Verification needed",
};

const escapeCell = value => String(value).replaceAll("|", "\\|").replaceAll("\n", " ");

export function render(manifest) {
  const groups = new Map();
  for (const capability of manifest.capabilities) {
    if (!groups.has(capability.group)) groups.set(capability.group, []);
    groups.get(capability.group).push(capability);
  }

  const lines = [
    "# Community feature matrix",
    "",
    "> Generated from `community/capabilities.yml`. Do not edit this file directly.",
    "",
    "This matrix compares API-level availability, not managed-service guarantees. A feature is only marked **Available** after it has a provider-neutral implementation and a self-host compatibility test. **Configurable** means the API path is public but requires an operator-supplied service or model.",
    "",
    "| Status | Meaning |",
    "| --- | --- |",
    ...Object.entries(manifest.statusDefinitions).map(([status, meaning]) =>
      `| ${labels[status] ?? status} | ${escapeCell(meaning)} |`,
    ),
    "",
  ];

  for (const [group, capabilities] of groups) {
    lines.push(`## ${group}`, "", "| Capability | Firecrawl Cloud | Community | Requirements | Evidence |", "| --- | --- | --- | --- | --- |");
    for (const item of capabilities) {
      lines.push(
        `| ${escapeCell(item.name)} | ${item.cloud ? "Yes" : "No"} | ${labels[item.community]} | ${escapeCell(item.requirements)} | ${escapeCell(item.evidence)} |`,
      );
    }
    lines.push("");
  }

  lines.push(
    "## Scope and evidence rules",
    "",
    "- Compatibility work uses public Firecrawl source, public documentation, published schemas and official SDK behavior.",
    "- No Firecrawl Cloud credentials or private endpoints are required by community CI.",
    "- Cloud-only infrastructure is not represented as open source parity. Operators may connect independent providers through documented adapters.",
    "- A regression changes the manifest status before a release is promoted.",
    "",
  );
  return `${lines.join("\n")}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rendered = render(loadManifest());
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
    if (current !== rendered) {
      console.error("COMMUNITY_FEATURES.md is stale. Run: node community/scripts/render-capabilities.mjs");
      process.exit(1);
    }
  } else {
    fs.writeFileSync(outputPath, rendered);
  }
}

-- Community operator dashboard v3: instance settings, cleanup and self-test
-- runs, alerting, in-app notifications, user preferences and user webhooks.

CREATE TABLE IF NOT EXISTS dashboard.setting (
  key text PRIMARY KEY,
  value jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid REFERENCES dashboard."user" ("id") ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS dashboard.cleanup_run (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job text NOT NULL,
  trigger text NOT NULL DEFAULT 'schedule',
  started_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  status text NOT NULL DEFAULT 'running',
  deleted_rows bigint,
  error text,
  CONSTRAINT cleanup_run_status_valid CHECK (status IN ('running', 'succeeded', 'failed', 'skipped'))
);

CREATE INDEX IF NOT EXISTS cleanup_run_job_started_idx
  ON dashboard.cleanup_run (job, started_at DESC);

CREATE TABLE IF NOT EXISTS dashboard.selftest_run (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  feature text NOT NULL,
  status text NOT NULL,
  latency_ms integer,
  detail text,
  run_by uuid REFERENCES dashboard."user" ("id") ON DELETE SET NULL,
  CONSTRAINT selftest_run_status_valid CHECK (status IN ('pass', 'fail', 'skip'))
);

CREATE INDEX IF NOT EXISTS selftest_run_feature_created_idx
  ON dashboard.selftest_run (feature, created_at DESC);

CREATE TABLE IF NOT EXISTS dashboard.alert_rule (
  id uuid DEFAULT gen_random_uuid() NOT NULL PRIMARY KEY,
  kind text NOT NULL,
  name text NOT NULL,
  threshold numeric NOT NULL,
  window_minutes integer NOT NULL DEFAULT 15,
  channels jsonb NOT NULL DEFAULT '{"inApp": true, "email": false, "webhook": false}'::jsonb,
  enabled boolean NOT NULL DEFAULT true,
  cooldown_minutes integer NOT NULL DEFAULT 60,
  last_fired_at timestamptz,
  created_by uuid REFERENCES dashboard."user" ("id") ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT alert_rule_kind_valid CHECK (
    kind IN ('error_rate', 'queue_backlog', 'service_down', 'credit_limit', 'agent_failures')
  ),
  CONSTRAINT alert_rule_window_positive CHECK (window_minutes > 0)
);

CREATE TABLE IF NOT EXISTS dashboard.alert_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  rule_id uuid REFERENCES dashboard.alert_rule ("id") ON DELETE SET NULL,
  kind text NOT NULL,
  severity text NOT NULL DEFAULT 'warning',
  subject_team_id uuid,
  message text NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  deliveries jsonb NOT NULL DEFAULT '[]'::jsonb
);

CREATE INDEX IF NOT EXISTS alert_event_created_idx ON dashboard.alert_event (created_at DESC);

CREATE TABLE IF NOT EXISTS dashboard.notification (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  user_id uuid NOT NULL REFERENCES dashboard."user" ("id") ON DELETE CASCADE,
  kind text NOT NULL,
  title text NOT NULL,
  body text,
  link text,
  dedupe_key text,
  read_at timestamptz
);

CREATE INDEX IF NOT EXISTS notification_user_created_idx
  ON dashboard.notification (user_id, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS notification_dedupe_idx
  ON dashboard.notification (user_id, dedupe_key)
  WHERE dedupe_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS dashboard.user_preference (
  user_id uuid PRIMARY KEY REFERENCES dashboard."user" ("id") ON DELETE CASCADE,
  limit_alerts boolean NOT NULL DEFAULT true,
  job_notifications boolean NOT NULL DEFAULT true,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS dashboard.user_webhook (
  id uuid DEFAULT gen_random_uuid() NOT NULL PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES dashboard."user" ("id") ON DELETE CASCADE,
  team_id uuid NOT NULL,
  url text NOT NULL,
  secret text NOT NULL,
  events text[] NOT NULL DEFAULT ARRAY['crawl', 'batch_scrape', 'agent'],
  enabled boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT user_webhook_url_length CHECK (char_length(url) <= 2048)
);

CREATE INDEX IF NOT EXISTS user_webhook_user_idx ON dashboard.user_webhook (user_id);

CREATE TABLE IF NOT EXISTS dashboard.webhook_delivery (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  webhook_id uuid REFERENCES dashboard.user_webhook ("id") ON DELETE CASCADE,
  target text NOT NULL,
  event text NOT NULL,
  status_code integer,
  success boolean NOT NULL,
  latency_ms integer,
  error text
);

CREATE INDEX IF NOT EXISTS webhook_delivery_webhook_idx
  ON dashboard.webhook_delivery (webhook_id, created_at DESC);

CREATE OR REPLACE FUNCTION public.change_tracking_insert_scrape(
  p_team_id uuid,
  p_url text,
  p_job_id text,
  p_change_tracking_tag text,
  p_date_added timestamptz
)
RETURNS bigint
LANGUAGE plpgsql
VOLATILE
SET search_path = public, pg_temp
AS $function$
DECLARE
  inserted_id bigint;
BEGIN
  INSERT INTO public.firecrawl_change_tracking_scrapes (
    team_id, url, job_id, change_tracking_tag, date_added
  ) VALUES (
    p_team_id, p_url, p_job_id, p_change_tracking_tag, p_date_added
  )
  RETURNING id INTO inserted_id;
  RETURN inserted_id;
END
$function$;

CREATE OR REPLACE FUNCTION public.diff_get_last_scrape_v7(
  i_team_id uuid,
  i_url text,
  i_tag text
)
RETURNS TABLE (o_job_id text, o_date_added timestamptz)
LANGUAGE sql
STABLE
SET search_path = public, pg_temp
AS $function$
  SELECT ct.job_id, ct.date_added
  FROM public.firecrawl_change_tracking_scrapes ct
  WHERE ct.team_id = i_team_id
    AND ct.url = i_url
    AND ct.change_tracking_tag IS NOT DISTINCT FROM i_tag
  ORDER BY ct.date_added DESC
  LIMIT 1
$function$;


CREATE OR REPLACE FUNCTION public.monitoring_claim_due_monitors(
  p_worker_id text,
  p_limit integer,
  p_lease_seconds integer
)
RETURNS SETOF public.monitors
LANGUAGE plpgsql
VOLATILE
SET search_path = public, pg_temp
AS $function$
BEGIN
  RETURN QUERY
  WITH due AS (
    SELECT m.id
    FROM public.monitors m
    WHERE m.status = 'active'
      AND m.deleted_at IS NULL
      AND m.next_run_at IS NOT NULL
      AND m.next_run_at <= now()
      AND (m.locked_until IS NULL OR m.locked_until < now())
    ORDER BY m.next_run_at
    FOR UPDATE SKIP LOCKED
    LIMIT GREATEST(p_limit, 0)
  )
  UPDATE public.monitors m
  SET locked_at = now(),
      locked_until = now() + make_interval(secs => GREATEST(p_lease_seconds, 1)),
      updated_at = now()
  FROM due
  WHERE m.id = due.id
  RETURNING m.*;
END
$function$;


CREATE OR REPLACE FUNCTION public.auth_chunk_1(
  input_key text,
  input_credential_purpose text DEFAULT 'general'
)
RETURNS TABLE (
  api_key text,
  api_key_id bigint,
  team_id uuid,
  org_id uuid,
  flags jsonb,
  is_banned boolean
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $function$
  SELECT
    k.key::text,
    k.id,
    t.id,
    t.org_id,
    public.selfhost_unlimited_rate_limit_flags(),
    COALESCE(t.banned, false)
  FROM public.api_keys k
  JOIN public.teams t ON t.id = k.team_id
  WHERE k.key::text = input_key
  LIMIT 1
$function$;

CREATE OR REPLACE FUNCTION public.auth_chunk_1_from_team(input_team text)
RETURNS TABLE (
  api_key text,
  api_key_id bigint,
  team_id uuid,
  org_id uuid,
  flags jsonb,
  is_banned boolean
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $function$
  SELECT
    k.key::text,
    k.id,
    t.id,
    t.org_id,
    public.selfhost_unlimited_rate_limit_flags(),
    COALESCE(t.banned, false)
  FROM public.teams t
  LEFT JOIN LATERAL (
    SELECT ak.id, ak.key
    FROM public.api_keys ak
    WHERE ak.team_id = t.id
    ORDER BY ak.id
    LIMIT 1
  ) k ON true
  WHERE t.id = input_team::uuid
  LIMIT 1
$function$;


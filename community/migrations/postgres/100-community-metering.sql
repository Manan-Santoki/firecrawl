-- Provider-neutral request log, credit ledger and per-team limits for the
-- community distribution. Upstream v2.11.739 publishes its job log only to
-- Pub/Sub and meters credits only through Firecrawl Cloud billing, so a
-- self-hosted deployment otherwise keeps no request history and cannot
-- enforce credit limits. Everything lives in its own `community` schema so it
-- never collides with upstream tables.

CREATE SCHEMA IF NOT EXISTS community;

-- One row per HTTP request to a versioned API route, written asynchronously
-- by the API's community request-log middleware.
CREATE TABLE IF NOT EXISTS community.request_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  team_id uuid,
  api_key_id bigint,
  method text NOT NULL,
  endpoint text NOT NULL,
  path text NOT NULL,
  api_version text,
  target text,
  status_code integer NOT NULL,
  duration_ms integer NOT NULL,
  job_id text,
  error text,
  origin text,
  zero_data_retention boolean NOT NULL DEFAULT false,
  CONSTRAINT request_log_target_length CHECK (char_length(target) <= 2048),
  CONSTRAINT request_log_error_length CHECK (char_length(error) <= 4096)
);

CREATE INDEX IF NOT EXISTS request_log_created_at_idx
  ON community.request_log (created_at);
CREATE INDEX IF NOT EXISTS request_log_team_created_idx
  ON community.request_log (team_id, created_at DESC);
CREATE INDEX IF NOT EXISTS request_log_key_created_idx
  ON community.request_log (api_key_id, created_at DESC);
CREATE INDEX IF NOT EXISTS request_log_job_id_idx
  ON community.request_log (job_id)
  WHERE job_id IS NOT NULL;

-- One row per credit charge the API makes (the same events Firecrawl Cloud
-- sends to its billing service). Async work such as crawl pages is charged
-- here as it completes, keyed by the originating job id.
CREATE TABLE IF NOT EXISTS community.credit_usage (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  team_id uuid NOT NULL,
  api_key_id bigint,
  endpoint text NOT NULL,
  job_id text,
  credits numeric(14, 2) NOT NULL
);

CREATE INDEX IF NOT EXISTS credit_usage_team_created_idx
  ON community.credit_usage (team_id, created_at DESC);
CREATE INDEX IF NOT EXISTS credit_usage_key_created_idx
  ON community.credit_usage (api_key_id, created_at DESC);
CREATE INDEX IF NOT EXISTS credit_usage_job_id_idx
  ON community.credit_usage (job_id)
  WHERE job_id IS NOT NULL;

-- Operator-set limits for a team (one team per dashboard user). Per-key
-- limits stay on public.api_keys (credit_limit, credit_limit_interval,
-- concurrency) where upstream defines them.
CREATE TABLE IF NOT EXISTS community.team_limits (
  team_id uuid PRIMARY KEY REFERENCES public.teams (id) ON DELETE CASCADE,
  credit_limit integer,
  credit_limit_interval text,
  concurrency_limit integer,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by text,
  CONSTRAINT team_limits_credit_limit_positive CHECK (credit_limit IS NULL OR credit_limit >= 0),
  CONSTRAINT team_limits_interval_valid CHECK (
    credit_limit_interval IS NULL OR credit_limit_interval IN ('day', 'week', 'month')
  ),
  CONSTRAINT team_limits_credit_pair CHECK (
    (credit_limit IS NULL) = (credit_limit_interval IS NULL)
  ),
  CONSTRAINT team_limits_concurrency_positive CHECK (
    concurrency_limit IS NULL OR concurrency_limit > 0
  )
);

-- Start of the current calendar window (UTC). Unknown intervals are treated
-- as monthly so a malformed key interval can never silently disable a limit.
CREATE OR REPLACE FUNCTION community.credit_window_start(
  p_interval text,
  p_at timestamptz DEFAULT now()
)
RETURNS timestamptz
LANGUAGE sql
STABLE
AS $function$
  SELECT date_trunc(
    CASE WHEN p_interval IN ('day', 'week', 'month') THEN p_interval ELSE 'month' END,
    p_at AT TIME ZONE 'UTC'
  ) AT TIME ZONE 'UTC'
$function$;

-- Everything the API's credit gate needs in one round trip: the team limit,
-- the key limit and the credits each has used in its current window.
CREATE OR REPLACE FUNCTION community.credit_gate_state(
  p_team_id uuid,
  p_api_key_id bigint
)
RETURNS TABLE (
  team_limit integer,
  team_interval text,
  team_used numeric,
  key_limit integer,
  key_interval text,
  key_used numeric
)
LANGUAGE sql
STABLE
SET search_path = community, public, pg_temp
AS $function$
  WITH tl AS (
    SELECT l.credit_limit, l.credit_limit_interval
    FROM community.team_limits l
    WHERE l.team_id = p_team_id
  ),
  kl AS (
    SELECT k.credit_limit, k.credit_limit_interval
    FROM public.api_keys k
    WHERE k.id = p_api_key_id
      AND k.team_id = p_team_id
      AND k.credit_limit IS NOT NULL
  )
  SELECT
    tl.credit_limit,
    tl.credit_limit_interval,
    CASE WHEN tl.credit_limit IS NULL THEN NULL ELSE (
      SELECT COALESCE(sum(u.credits), 0)
      FROM community.credit_usage u
      WHERE u.team_id = p_team_id
        AND u.created_at >= community.credit_window_start(tl.credit_limit_interval)
    ) END,
    kl.credit_limit,
    COALESCE(kl.credit_limit_interval, CASE WHEN kl.credit_limit IS NULL THEN NULL ELSE 'month' END),
    CASE WHEN kl.credit_limit IS NULL THEN NULL ELSE (
      SELECT COALESCE(sum(u.credits), 0)
      FROM community.credit_usage u
      WHERE u.team_id = p_team_id
        AND u.api_key_id = p_api_key_id
        AND u.created_at >= community.credit_window_start(kl.credit_limit_interval)
    ) END
  FROM (SELECT 1) AS anchor
  LEFT JOIN tl ON true
  LEFT JOIN kl ON true
$function$;

-- Deletes request-log rows older than the retention window, in bounded
-- batches so a large backlog never holds a long lock. The credit ledger is
-- kept for at least 62 days so monthly limits always see a full window.
CREATE OR REPLACE FUNCTION community.purge_expired(
  p_retention_days integer,
  p_batch_size integer DEFAULT 5000,
  p_max_batches integer DEFAULT 100
)
RETURNS TABLE (request_log_deleted bigint, credit_usage_deleted bigint)
LANGUAGE plpgsql
VOLATILE
SET search_path = community, pg_temp
AS $function$
DECLARE
  log_cutoff timestamptz := now() - make_interval(days => GREATEST(p_retention_days, 1));
  ledger_cutoff timestamptz := now() - make_interval(days => GREATEST(p_retention_days, 62));
  batch_deleted bigint;
  batches integer := 0;
BEGIN
  request_log_deleted := 0;
  credit_usage_deleted := 0;
  LOOP
    DELETE FROM community.request_log
    WHERE id IN (
      SELECT id FROM community.request_log
      WHERE created_at < log_cutoff
      LIMIT GREATEST(p_batch_size, 1)
    );
    GET DIAGNOSTICS batch_deleted = ROW_COUNT;
    request_log_deleted := request_log_deleted + batch_deleted;
    batches := batches + 1;
    EXIT WHEN batch_deleted = 0 OR batches >= p_max_batches;
  END LOOP;
  batches := 0;
  LOOP
    DELETE FROM community.credit_usage
    WHERE id IN (
      SELECT id FROM community.credit_usage
      WHERE created_at < ledger_cutoff
      LIMIT GREATEST(p_batch_size, 1)
    );
    GET DIAGNOSTICS batch_deleted = ROW_COUNT;
    credit_usage_deleted := credit_usage_deleted + batch_deleted;
    batches := batches + 1;
    EXIT WHEN batch_deleted = 0 OR batches >= p_max_batches;
  END LOOP;
  RETURN NEXT;
END
$function$;

REVOKE ALL ON SCHEMA community FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION community.credit_gate_state(uuid, bigint) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION community.purge_expired(integer, integer, integer) FROM PUBLIC;

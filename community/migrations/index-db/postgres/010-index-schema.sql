-- Scrape-index tables for the database behind INDEX_DATABASE_URL.
--
-- Column names, types, nullability and defaults mirror the Drizzle definitions
-- published upstream in apps/api/src/db/schema/index-db.ts (fingerprinted in
-- ../manifest.json). The index worker inserts rows with Drizzle, naming every
-- column, so these definitions must stay column-compatible with that file.

CREATE TABLE IF NOT EXISTS public.index (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  url text NOT NULL,
  url_hash bytea NOT NULL,
  original_url text NOT NULL,
  resolved_url text NOT NULL,
  has_screenshot boolean NOT NULL,
  has_screenshot_fullscreen boolean NOT NULL,
  is_mobile boolean NOT NULL,
  block_ads boolean NOT NULL,
  location_country text,
  location_languages text[],
  status integer NOT NULL,
  title text,
  description text,
  invalidated_at timestamptz,
  is_precrawl boolean,
  wait_time_ms bigint,
  is_stealth boolean NOT NULL DEFAULT false,
  url_split_0_hash bytea NOT NULL,
  url_split_1_hash bytea,
  url_split_2_hash bytea,
  url_split_3_hash bytea,
  url_split_4_hash bytea,
  url_split_5_hash bytea,
  url_split_6_hash bytea,
  url_split_7_hash bytea,
  url_split_8_hash bytea,
  url_split_9_hash bytea,
  domain_splits_0_hash bytea,
  domain_splits_1_hash bytea,
  domain_splits_2_hash bytea,
  domain_splits_3_hash bytea,
  domain_splits_4_hash bytea
);

-- Hot path: index_get_recent_5 (URL -> newest entries of one variant).
CREATE INDEX IF NOT EXISTS index_url_hash_created_at_idx
  ON public.index (url_hash, created_at DESC);

-- Map / crawl discovery by URL-prefix level and by domain level.
CREATE INDEX IF NOT EXISTS index_url_split_0_hash_idx ON public.index (url_split_0_hash, created_at DESC);

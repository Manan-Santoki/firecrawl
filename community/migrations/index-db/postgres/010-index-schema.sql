CREATE INDEX IF NOT EXISTS index_url_split_2_hash_idx ON public.index (url_split_2_hash, created_at DESC) WHERE url_split_2_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS index_url_split_3_hash_idx ON public.index (url_split_3_hash, created_at DESC) WHERE url_split_3_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS index_url_split_4_hash_idx ON public.index (url_split_4_hash, created_at DESC) WHERE url_split_4_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS index_url_split_5_hash_idx ON public.index (url_split_5_hash, created_at DESC) WHERE url_split_5_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS index_url_split_6_hash_idx ON public.index (url_split_6_hash, created_at DESC) WHERE url_split_6_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS index_url_split_7_hash_idx ON public.index (url_split_7_hash, created_at DESC) WHERE url_split_7_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS index_url_split_8_hash_idx ON public.index (url_split_8_hash, created_at DESC) WHERE url_split_8_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS index_url_split_9_hash_idx ON public.index (url_split_9_hash, created_at DESC) WHERE url_split_9_hash IS NOT NULL;

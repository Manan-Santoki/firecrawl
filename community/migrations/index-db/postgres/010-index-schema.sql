-- Age-based retention (community_index_prune).
CREATE INDEX IF NOT EXISTS index_created_at_idx ON public.index (created_at);

CREATE TABLE IF NOT EXISTS public.engpicker_queue (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  domain_hash bytea NOT NULL,
  domain_level integer NOT NULL,
  picked_up_at timestamptz,
  done boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS engpicker_queue_domain_hash_idx
  ON public.engpicker_queue (domain_hash, created_at DESC);
CREATE INDEX IF NOT EXISTS engpicker_queue_unpicked_idx
  ON public.engpicker_queue (created_at DESC) WHERE picked_up_at IS NULL;

CREATE TABLE IF NOT EXISTS public.engpicker_verdicts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  domain_hash bytea NOT NULL,
  verdict varchar NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS engpicker_verdicts_domain_hash_idx
  ON public.engpicker_verdicts (domain_hash, created_at DESC);

-- Community-owned inputs for functions whose upstream data source is not
-- published. Both are empty by default, which reproduces the API's own
-- "no data" fallbacks (2-day default maxAge, no OMCE signatures).

-- Per-domain dynamic maxAge served by query_max_age(). domain_hash is the
-- SHA-256 of the most specific domain split, i.e. hashURL of
-- generateDomainSplits(hostname).at(-1) (the full hostname without "www.").
CREATE TABLE IF NOT EXISTS public.community_domain_max_age (
  domain_hash bytea PRIMARY KEY,
  max_age bigint NOT NULL CHECK (max_age > 0),
  note text,
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Boilerplate signatures served by query_omce_signatures() to htmlTransform
-- when a scrape sets __experimental_omce.
CREATE TABLE IF NOT EXISTS public.community_omce_signatures (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  domain_hash bytea NOT NULL,
  signature text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS community_omce_signatures_domain_hash_idx
  ON public.community_omce_signatures (domain_hash, created_at DESC);
